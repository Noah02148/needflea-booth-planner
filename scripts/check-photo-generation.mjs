// Environment input-method regression. The former Codex photo-generation UI is retired.
import assert from 'node:assert/strict';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import puppeteer from 'puppeteer';
import sharp from 'sharp';
const dir = await mkdtemp(join(tmpdir(), 'needflea-environment-methods-'));
const browser = await puppeteer.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage(); page.setDefaultTimeout(60000);
  await page.setViewport({ width: 1440, height: 1000 });
  const errors = [], oldRequests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (r.url().includes(':3003')) oldRequests.push(r.url()); });
  const project = { version: 3, metersPerUnit: 1, items: [], nextId: 1 };
  const file = join(dir, 'legacy.json'); await writeFile(file, JSON.stringify(project));
  const photo = join(dir, 'photo.jpg'); await sharp({create:{width:96,height:96,channels:3,background:'#aaa899'}}).jpeg().toFile(photo);
  await page.goto(process.env.NEEDFLEA_URL || 'http://127.0.0.1:3002', { waitUntil: 'networkidle0' });
  await (await page.$('#load-input')).uploadFile(file);
  await page.click('#btn-environment');
  await page.waitForFunction(() => _3dMode && !document.querySelector('#btn-3d').disabled);
  assert.equal(await page.$eval('#env-manual-panel', e => e.hidden), false);
  assert.equal(await page.$eval('#env-marble-panel', e => e.hidden), true);
  assert.equal(await page.$('#env-generate'), null, 'Only the two requested methods are offered');
  await page.evaluate(() => { const s = environmentUI.snapshot(); s.analysis={summary:'旧项目记录',model:'legacy',observations:[],assumptions:[],questions:[]}; s.generationPrompt='历史要求'; s.objects=[{id:1,type:'column',name:'实测柱',x:4,y:4,width:.6,depth:.6,height:4.2,angle:0}]; environmentUI.restore(s); render(); });
  await page.screenshot({ path: join(dir, 'manual-method.png') });
  const before = await page.evaluate(() => environmentUI.snapshot());
  await page.click('#env-method-marble');
  assert.equal(await page.$eval('#env-manual-panel', e => e.hidden), true);
  assert.equal(await page.$eval('#env-marble-panel', e => e.hidden), false);
  assert.deepEqual(await page.evaluate(() => environmentUI.snapshot()), before);
  await (await page.$('#env-photos')).uploadFile(photo);
  await page.waitForFunction(() => environmentUI.snapshot().photos.length === 1);
  await page.type('#env-notes', '保留砖墙，层高实测 4.2 米');
  const withPhoto = await page.evaluate(() => environmentUI.snapshot());
  await page.click('#env-method-manual');
  await page.click('[data-env-add="wall"]');
  await page.click('#env-method-marble');
  assert.equal(await page.$eval('#env-cancel', e => e.hidden), true, 'Changing method cancels unfinished placement');
  assert.deepEqual(await page.evaluate(() => environmentUI.snapshot()), withPhoto, 'Switching preserves photos, measurements and legacy data');
  await page.screenshot({ path: join(dir, 'marble-method.png') });
  await page.focus('#env-method-marble'); await page.keyboard.press('ArrowLeft');
  assert.equal(await page.$eval('#env-method-manual', e => e.getAttribute('aria-selected')), 'true');
  assert.deepEqual(errors, []); assert.deepEqual(oldRequests, [], 'No connection or generation requests to the retired Codex service');
  console.log('PASS: two methods, field visibility, manual structure and photo retention, keyboard navigation, legacy data compatibility, no Codex calls. Artifacts:', dir);
} finally { await browser.close(); }
