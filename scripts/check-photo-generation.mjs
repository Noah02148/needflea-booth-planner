// Historical filename: now checks the measured-plan -> scene-building workflow.
import assert from 'node:assert/strict';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import puppeteer from 'puppeteer';
const dir = await mkdtemp(join(tmpdir(), 'needflea-scene-workflow-'));
const browser = await puppeteer.launch({ headless:true, args:['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
try {
  const page=await browser.newPage(); page.setDefaultTimeout(30000);
  await page.setViewport({width:1440,height:1000});
  const errors=[], retired=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('request', r=>{ if(/:300[34]|marble|spark/i.test(r.url())) retired.push(r.url()); });
  page.on('dialog', d=>d.accept());
  const url=process.env.NEEDFLEA_URL||'http://127.0.0.1:3002';
  await page.goto(url,{waitUntil:'networkidle0'});
  await page.click('#btn-environment');
  assert.equal(await page.evaluate(()=>_3dMode),false);
  assert.equal(await page.$('#env-marble-panel'),null);
  await page.click('#env-source-measured');
  await page.click('#env-create-site');
  await page.waitForFunction(()=>dxfLoaded && metersPerUnit===1 && environmentUI.snapshot().sitePlan);
  const plan=await page.evaluate(()=>environmentUI.snapshot().sitePlan);
  assert.equal(plan.points[2].x,40); assert.equal(plan.points[2].y,25);
  assert.equal(await page.$eval('#welcome',e=>e.classList.contains('hidden')),true);
  const vertex = await page.evaluate(()=>({x:renderer.wx(0),y:renderer.wy(0)}));
  assert.ok(Number.isFinite(vertex.x) && Number.isFinite(vertex.y));
  await page.screenshot({path:join(dir,'measured-plan.png')});
  await page.click(await page.$eval('#env-base-panel', e => e.hidden) ? '#env-step-structure' : '#env-continue');
  await page.waitForFunction(()=>_3dMode && !document.querySelector('#btn-environment').disabled);
  await page.click('#env-view-2d');
  await page.click('[data-env-add="building"]');
  const clickWorld=async(x,y)=>{ const p=await page.evaluate((x,y)=>{const r=canvas.getBoundingClientRect();return {x:r.left+renderer.wx(x),y:r.top+renderer.wy(y)};},x,y); await page.mouse.click(p.x,p.y); };
  await clickWorld(10,16);
  await page.waitForFunction(()=>environmentUI.snapshot().objects.length===1);
  assert.equal(await page.evaluate(()=>environmentUI.snapshot().objects[0].scope),'site');
  await page.click('#toolbar-tab-layout');
  await page.click('#layout-tab-components');
  await page.click('#layout-component-properties');
  assert.equal(await page.evaluate(()=>_3dMode),false);
  await page.click('[data-env-add="truss"]'); await clickWorld(20,10);
  await page.waitForFunction(()=>environmentUI.snapshot().objects.length===2);
  await page.$eval('#env-object-editor input[name=elevation]',e=>{ e.value='0.6';e.dispatchEvent(new Event('change')); });
  assert.equal(await page.evaluate(()=>environmentUI.snapshot().objects[1].elevation),.6);
  await page.$eval('#env-object-editor input[type=text]',e=>{e.value='入口展亭';e.dispatchEvent(new Event('change'));});
  const position=await page.evaluate(()=>environmentUI.snapshot().objects[1]);
  await page.$$eval('#env-object-editor button', buttons=>buttons.find(b=>b.textContent==='在图中重新定位').click());
  await page.keyboard.press('Escape');
  assert.deepEqual(await page.evaluate(()=>environmentUI.snapshot().objects[1]),position);
  await page.$$eval('#env-object-editor button', buttons=>buttons.find(b=>b.textContent==='在图中重新定位').click());
  await clickWorld(21,9);
  assert.equal(await page.evaluate(()=>environmentUI.snapshot().objects[1].x),21);
  await page.$$eval('#env-object-editor button', buttons => buttons.find(b=>b.textContent==='复制组件').click());
  assert.equal(await page.evaluate(()=>environmentUI.snapshot().objects.length),3);
  await page.click('#btn-environment');
  await page.click('#env-step-export');
  await page.waitForFunction(()=>_3dMode && !document.querySelector('#btn-environment').disabled);
  await page.click('#env-human'); await page.type('#env-view-name','入口人视角'); await page.click('#env-view-save');
  const state=await page.evaluate(()=>environmentUI.snapshot());
  assert.equal(state.views[0].name,'入口人视角'); assert.ok(Math.abs(state.views[0].position[1]-1.65)<1e-9);
  await page.click('#env-overview'); await page.click('#env-view-list button');
  await page.click('#env-close');
  await page.screenshot({path:join(dir,'scene-components.png')});
  const project=await page.evaluate(()=>projectIO.capture());
  assert.equal(project.cadFile,null); assert.ok(project.venue.entities.length>=4);
  const file=join(dir,'measured-project.json'); await writeFile(file,JSON.stringify(project));
  await page.reload({waitUntil:'networkidle0'}); await (await page.$('#load-input')).uploadFile(file);
  await page.waitForFunction(()=>dxfLoaded && environmentUI.snapshot().objects.length===3);
  assert.deepEqual(await page.evaluate(()=>environmentUI.snapshot()),state);
  // Malformed geometry must fail before the current canvas changes.
  const before=await page.evaluate(()=>projectIO.capture(false));
  const rejection=await page.evaluate(async()=>{const p=projectIO.capture(false); p.environment.sitePlan.points=[{x:0,y:0},{x:10,y:10},{x:0,y:10},{x:10,y:0}]; try {await projectIO.load(p);return false;} catch {return true;} });
  assert.equal(rejection,true); assert.deepEqual(await page.evaluate(()=>projectIO.capture(false)),before);
  // Saving a scene with only activity components still creates a first activity.
  await page.click('#toolbar-tab-files');
  await page.click('#site-library-button');
  const idle=()=>page.waitForFunction(()=>document.querySelector('#site-library-dialog').getAttribute('aria-busy')==='false');
  await idle(); await page.$eval('#site-create-details',e=>e.open=true);
  await page.$eval('#site-name',e=>e.value='实测广场'); await page.select('#site-source','current');
  await page.click('#site-create'); await idle();
  const records=await page.evaluate(()=>new Promise((resolve,reject)=>{const r=indexedDB.open('needflea-site-library',2);r.onsuccess=()=>{const db=r.result,tx=db.transaction(['projects','activityProjects']);const b=tx.objectStore('projects').getAll(),a=tx.objectStore('activityProjects').getAll();tx.oncomplete=()=>{db.close();resolve({bases:b.result,activities:a.result});};tx.onerror=()=>reject(tx.error);};}));
  assert.equal(records.bases[0].project.environment.objects.length,1);
  assert.equal(records.bases[0].project.environment.views.length,0);
  assert.equal(records.activities[0].project.environment.objects.length,3);
  assert.equal(records.activities[0].project.environment.views.length,1);
  assert.deepEqual(records.bases[0].project.environment.sitePlan,plan);
  const annotations=join(dir,'annotations-only.json');await writeFile(annotations,JSON.stringify({version:3,items:[],nextId:1}));
  await page.$eval('#activity-create-details',e=>e.open=true);await page.$eval('#activity-name',e=>e.value='第二次活动');await page.select('#activity-source','file');
  await (await page.$('#activity-file')).uploadFile(annotations);await page.click('#activity-create');await idle();
  assert.equal(await page.evaluate(()=>environmentUI.snapshot().objects.length),1);
  assert.deepEqual(await page.evaluate(()=>environmentUI.snapshot().sitePlan),plan);
  await page.click('#site-close');
  // A CAD/image-less legacy project must clear the measured boundary.
  await page.evaluate(()=>projectIO.load({version:3,items:[],metersPerUnit:1}));
  assert.equal(await page.evaluate(()=>environmentUI.snapshot().sitePlan),null);
  assert.equal(await page.evaluate(()=>renderer.dxfData),null);
  await (await page.$('#load-input')).uploadFile(file); await page.waitForFunction(()=>dxfLoaded);
  await page.click('#btn-environment');
  const original=await page.evaluate(()=>environmentUI.snapshot());
  await page.focus('#env-step-structure'); await page.keyboard.press('ArrowRight');
  await page.waitForFunction(()=>_3dMode && !document.querySelector('#btn-environment').disabled);
  assert.equal(await page.$eval('#env-step-export',e=>e.getAttribute('aria-selected')),'true');
  assert.deepEqual(await page.evaluate(()=>environmentUI.snapshot()),original);
  await page.setViewport({width:390,height:844});
  await page.screenshot({path:join(dir,'mobile-workflow.png')});
  const box=await page.$eval('#environment-panel',e=>({left:e.getBoundingClientRect().left,right:e.getBoundingClientRect().right,scroll:e.scrollWidth,client:e.clientWidth}));
  assert.ok(box.left>=0 && box.right<=390 && box.scroll<=box.client+1);
  const routed=await page.evaluate(()=>environmentUI.snapshot());
  await page.click('#env-step-base');
  assert.equal(await page.$eval('#env-base-panel',e=>e.hidden),false);
  assert.equal(await page.$eval('.env-methods',e=>e.hidden),true);
  assert.equal(await page.$eval('#toolbar-tab-files',e=>e.getAttribute('aria-selected')),'true');
  assert.equal(await page.evaluate(()=>_3dMode),false);
  assert.deepEqual(await page.evaluate(()=>environmentUI.snapshot()),routed,'Returning to site setup preserves the full scene');
  await page.screenshot({path:join(dir,'mobile-site-setup.png')});
  await page.click('#env-continue');
  await page.waitForFunction(()=>_3dMode && !document.querySelector('#btn-environment').disabled);
  assert.deepEqual(await page.evaluate(()=>environmentUI.snapshot()),routed);
  assert.deepEqual(errors,[]); assert.deepEqual(retired,[]);
  console.log('PASS: measured plan, fixed/activity components, exact elevation, copy, views, project roundtrip, invalid/legacy reset, keyboard, mobile, no retired requests. Artifacts:',dir);
} finally {await browser.close();}
